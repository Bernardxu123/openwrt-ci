# -*- coding: utf-8 -*-
"""Build assets for the home network planning web app."""
import cv2, numpy as np, base64, io
from PIL import Image

SRC = r"C:\Users\29049\.dsh\attachments\v1\objects\8f\8fa3257355e465e8d07538925423eb9ec8ad98372bd044baedec9f7d0e346b2c"
OUT = r"D:\AI\路由\netplan"

img = cv2.imread(SRC, cv2.IMREAD_GRAYSCALE)
h, w = img.shape
M = cv2.getRotationMatrix2D((w/2, h/2), 1.22, 1.0)
rot = cv2.warpAffine(img, M, (w, h), flags=cv2.INTER_CUBIC, borderValue=255)
crop = rot[120:1140, 430:1450]
ch, cw = crop.shape
assert (cw, ch) == (1020, 1020)

cl = crop.astype(np.float32)
bg = cv2.GaussianBlur(cl, (0, 0), 25)
n2 = np.clip((cl / np.maximum(bg, 1) * 255.0 - 150) * (255.0 / 60.0), 0, 255).astype(np.uint8)
ink = (n2 < 128).astype(np.uint8)

Hs = cv2.morphologyEx(ink, cv2.MORPH_OPEN, cv2.getStructuringElement(cv2.MORPH_RECT, (19, 1)))
Vs = cv2.morphologyEx(ink, cv2.MORPH_OPEN, cv2.getStructuringElement(cv2.MORPH_RECT, (1, 19)))
# bridge scan dashes (<=9px) along each axis; door openings are 20-45px so they survive
Hs = cv2.morphologyEx(Hs, cv2.MORPH_CLOSE, cv2.getStructuringElement(cv2.MORPH_RECT, (11, 1)))
Vs = cv2.morphologyEx(Vs, cv2.MORPH_CLOSE, cv2.getStructuringElement(cv2.MORPH_RECT, (1, 11)))
struct = cv2.bitwise_or(Hs, Vs)

N = 256
cell = cw / N
cov = np.zeros((N, N), np.float32)
for gy in range(N):
    y0 = int(round(gy * cell)); y1 = int(round((gy + 1) * cell))
    for gx in range(N):
        x0 = int(round(gx * cell)); x1 = int(round((gx + 1) * cell))
        cov[gy, gx] = struct[y0:y1, x0:x1].mean()
lvl = np.where(cov >= 0.42, 2, np.where(cov >= 0.10, 1, 0)).astype(np.uint8)
print("grid levels:", np.bincount(lvl.ravel()))

packed = bytearray()
for gy in range(N):
    row = lvl[gy]
    for gx in range(0, N, 4):
        b = 0
        for k in range(4):
            b |= int(row[gx + k]) << (2 * k)
        packed.append(b)
wall_b64 = base64.b64encode(bytes(packed)).decode("ascii")
print("wall grid bytes", len(packed), "b64", len(wall_b64))

UP = 2
gray = Image.fromarray(n2).resize((cw * UP, ch * UP), Image.LANCZOS)
a = np.array(gray).astype(np.uint8)
alpha = np.clip((255 - a).astype(np.float32) * 1.35, 0, 255).astype(np.uint8)
rgba = np.dstack([np.full_like(alpha, 255), np.full_like(alpha, 255), np.full_like(alpha, 255), alpha])
im = Image.fromarray(rgba, "RGBA")
buf = io.BytesIO(); im.save(buf, "PNG", optimize=True)
plan_png = buf.getvalue()
plan_b64 = base64.b64encode(plan_png).decode("ascii")
print("plan png", len(plan_png), "b64", len(plan_b64))

with open(OUT + r"\build\assets.js", "w", encoding="utf-8") as f:
    f.write("// auto-generated by build.py - do not edit\n")
    f.write("export const PLAN_PNG = '%s';\n" % plan_b64)
    f.write("export const WALL_GRID = '%s';\n" % wall_b64)
    f.write("export const GRID_N = %d;\n" % N)

px_per_m = 80.0
xs, ys = np.nonzero(ink)
print("ink bbox", xs.min(), xs.max(), ys.min(), ys.max())
print("extent %.2f x %.2f m" % ((xs.max()-xs.min())/px_per_m, (ys.max()-ys.min())/px_per_m))
